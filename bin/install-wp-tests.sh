#!/usr/bin/env bash
#
# One-time setup for the PHPUnit suite.
#
# Creates the test database inside the Local by WP Engine site's MySQL server and
# writes tests/wp-tests-config.php. The WordPress test library itself comes from
# the wp-phpunit Composer package, so no SVN checkout of core is needed.
#
# Usage: ./bin/install-wp-tests.sh
#
set -euo pipefail

PLUGIN_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PLUGIN_SLUG="$(basename "$PLUGIN_DIR")"
LOCAL_SUPPORT="$HOME/Library/Application Support/Local"
SITES_JSON="$LOCAL_SUPPORT/sites.json"
DB_NAME="${WTSYNC_TEST_DB:-woo_temu_tests}"

die() {
	echo "install-wp-tests: $1" >&2
	exit 1
}

command -v jq >/dev/null 2>&1 || die "jq is required but was not found on PATH."
[ -f "$SITES_JSON" ] || die "Local's sites.json not found at $SITES_JSON."

# Find the Local site whose plugins directory links back to this checkout.
SITE_ID=""
SITE_PATH=""
while IFS=$'\t' read -r id path; do
	path="${path/#\~/$HOME}"
	link="$path/app/public/wp-content/plugins/$PLUGIN_SLUG"
	if [ -e "$link" ] && [ "$(cd "$link" && pwd -P)" = "$PLUGIN_DIR" ]; then
		SITE_ID="$id"
		SITE_PATH="$path"
		break
	fi
done < <(jq -r 'to_entries[] | [.value.id, .value.path] | @tsv' "$SITES_JSON")

[ -n "$SITE_ID" ] || die "No Local site links to $PLUGIN_DIR."

WP_ROOT="$SITE_PATH/app/public"
[ -f "$WP_ROOT/wp-load.php" ] || die "No WordPress install at $WP_ROOT."
[ -f "$WP_ROOT/wp-content/plugins/woocommerce/woocommerce.php" ] || die "WooCommerce is not installed in $WP_ROOT."

DB_USER="$(jq -r --arg id "$SITE_ID" '.[$id].mysql.user' "$SITES_JSON")"
DB_PASS="$(jq -r --arg id "$SITE_ID" '.[$id].mysql.password' "$SITES_JSON")"
MYSQL_VERSION="$(jq -r --arg id "$SITE_ID" '.[$id].services.mysql.version' "$SITES_JSON")"

# Local grants its MySQL user socket access only; a TCP connection to 127.0.0.1 is
# rejected with "Host is not allowed to connect to this MySQL server".
SOCKET="$LOCAL_SUPPORT/run/$SITE_ID/mysql/mysqld.sock"
[ -S "$SOCKET" ] || die "MySQL socket not found at $SOCKET. Start the site in Local and try again."

# Local bundles its own MySQL client; there is none on PATH.
MYSQL_BIN=""
for candidate in "$LOCAL_SUPPORT/lightning-services/mysql-$MYSQL_VERSION"*/bin/*/bin/mysql; do
	if [ -x "$candidate" ]; then
		MYSQL_BIN="$candidate"
		break
	fi
done
[ -n "$MYSQL_BIN" ] || die "Local's MySQL $MYSQL_VERSION client not found."

# The test suite drops and recreates every table it uses, so it must never point at
# the site's own database.
SITE_DB="$(jq -r --arg id "$SITE_ID" '.[$id].mysql.database' "$SITES_JSON")"
[ "$DB_NAME" != "$SITE_DB" ] || die "Refusing to use the site's own database ($SITE_DB) for tests."

echo "Creating test database '$DB_NAME'…"
MYSQL_PWD="$DB_PASS" "$MYSQL_BIN" --protocol=SOCKET --socket="$SOCKET" -u "$DB_USER" \
	-e "CREATE DATABASE IF NOT EXISTS \`$DB_NAME\` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;"

CONFIG="$PLUGIN_DIR/tests/wp-tests-config.php"
echo "Writing $CONFIG…"
cat > "$CONFIG" <<PHP
<?php
/**
 * Generated by bin/install-wp-tests.sh — do not edit or commit.
 *
 * @package WooTemuSync
 */

define( 'ABSPATH', '$WP_ROOT/' );

define( 'DB_NAME', '$DB_NAME' );
define( 'DB_USER', '$DB_USER' );
define( 'DB_PASSWORD', '$DB_PASS' );
define( 'DB_HOST', 'localhost:$SOCKET' );
define( 'DB_CHARSET', 'utf8mb4' );
define( 'DB_COLLATE', '' );

\$table_prefix = 'wptests_';

define( 'WP_TESTS_DOMAIN', 'testshop.local' );
define( 'WP_TESTS_EMAIL', 'admin@testshop.local' );
define( 'WP_TESTS_TITLE', 'Woo Temu Sync Test Suite' );
define( 'WP_PHP_BINARY', 'php' );

define( 'WP_DEBUG', true );
define( 'WP_TESTS_PHPUNIT_POLYFILLS_PATH', '$PLUGIN_DIR/vendor/yoast/phpunit-polyfills' );
PHP

echo "Done. Run 'composer test'."
